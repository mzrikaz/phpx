<?php
// Generate crates/interp/src/date/zones_table.rs: PHP's time zone
// identifiers in its index order, flagging the canonical ones
// (timezone_identifiers_list()) apart from the backward-compatible aliases
// DateTimeZone::ALL_WITH_BC adds, with each canonical zone's country code.
//
//     php -n tools/date/zones.php > crates/interp/src/date/zones_table.rs

$canonical = array_flip(DateTimeZone::listIdentifiers(DateTimeZone::ALL));

echo "// @generated by tools/date/zones.php from PHP ", PHP_VERSION, " (timezonedb ", timezone_version_get(), "). Do not edit.\n\n";
echo "/// (identifier, canonical, ISO country code or \"??\").\n";
echo "pub static ZONES: &[(&str, bool, &str)] = &[\n";
foreach (DateTimeZone::listIdentifiers(DateTimeZone::ALL_WITH_BC) as $id) {
    $c = isset($canonical[$id]);
    $cc = $c ? ((new DateTimeZone($id))->getLocation()['country_code'] ?? '??') : '??';
    echo "    (\"$id\", ", $c ? 'true' : 'false', ", \"$cc\"),\n";
}
echo "];\n";
