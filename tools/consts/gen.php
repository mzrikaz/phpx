<?php
// Generate crates/interp/src/consts_table.rs: the constants of the
// extensions phpx implements, as PHP itself defines them.
//
//     php -n tools/consts/gen.php > crates/interp/src/consts_table.rs
//
// Constants phpx defines itself take precedence over these.

$exts = ['Core', 'standard', 'pcre', 'date', 'json', 'SPL', 'ctype', 'filter', 'hash', 'mbstring', 'zlib', 'random', 'iconv', 'session', 'tokenizer'];
$skip = ['TRUE', 'FALSE', 'NULL'];

function lit(string $s): string
{
    $out = '';
    foreach (str_split($s) as $c) {
        $o = ord($c);
        $out .= match (true) {
            $c === '\\' => '\\\\',
            $c === '"' => '\\"',
            $o < 0x20 || $o >= 0x7f => sprintf('\\x%02x', $o),
            default => $c,
        };
    }
    return '"' . $out . '"';
}

$all = get_defined_constants(true);
echo "// @generated by tools/consts/gen.php from PHP ", PHP_VERSION, ". Do not edit.\n\n";
echo "use crate::consts::C;\n\n";
echo "/// (name, value) of every constant of the implemented extensions.\n";
echo "pub static CONSTS: &[(&str, C)] = &[\n";
foreach ($exts as $e) {
    foreach ($all[$e] ?? [] as $k => $v) {
        if (in_array($k, $skip, true)) {
            continue;
        }
        $val = match (true) {
            is_int($v) => $v === PHP_INT_MIN ? 'C::I(i64::MIN)' : "C::I($v)",
            is_float($v) => is_nan($v) ? 'C::F(f64::NAN)' : (is_infinite($v) ? 'C::F(f64::INFINITY)' : 'C::F(' . var_export($v, true) . ')'),
            is_string($v) => 'C::S(' . lit($v) . ')',
            is_bool($v) => 'C::B(' . ($v ? 'true' : 'false') . ')',
            default => 'C::N',
        };
        echo "    (", lit($k), ", $val),\n";
    }
}
echo "];\n";
