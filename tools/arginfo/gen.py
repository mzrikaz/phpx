#!/usr/bin/env python3
"""Generate crates/interp/src/arginfo_table.rs from PHP's own Reflection.

    php -n tools/arginfo/dump.php > /tmp/arginfo.json
    tools/arginfo/gen.py /tmp/arginfo.json

Each entry: function name, then its parameters as (name, type, flags,
default) where type is PHP's declared type string ("" = untyped), flags
are 1 optional, 2 by-reference, 4 variadic, and default is the default
value's PHP source ("" = none known).
"""
import json, sys, os

src = json.load(open(sys.argv[1]))
out = os.path.join(os.path.dirname(__file__), '../../crates/interp/src/arginfo_table.rs')

def lit(s):
    out = []
    for c in s:
        if c == '\\':
            out.append('\\\\')
        elif c == '"':
            out.append('\\"')
        elif ord(c) < 0x20 or ord(c) == 0x7f:
            out.append('\\x%02x' % ord(c))
        else:
            out.append(c)
    return '"' + ''.join(out) + '"'

lines = [
    '// @generated by tools/arginfo/gen.py from PHP 8.5 Reflection. Do not edit.',
    '',
    '/// (function, [(parameter, type, flags, default)]): flags 1 optional,',
    '/// 2 by-reference, 4 variadic; "" type = untyped, "" default = unknown.',
    'pub static FUNCS: &[(&str, &[(&str, &str, u8, &str)])] = &[',
]
for f in sorted(src, key=lambda f: f['name']):
    ps = []
    for p in f['params']:
        flags = (1 if p['opt'] else 0) | (2 if p['ref'] else 0) | (4 if p['var'] else 0)
        ps.append('(%s, %s, %d, %s)' % (lit(p['name']), lit(p['type'] or ''), flags, lit(p['def'] or '')))
    lines.append('    (%s, &[%s]),' % (lit(f['name']), ', '.join(ps)))
lines.append('];')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f"{len(src)} functions -> {out}")
