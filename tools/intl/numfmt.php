<?php
// Generate crates/interp/src/intl/locales_table.rs: what NumberFormatter
// needs from ICU's locale data, read from PHP's own ext/intl.
//
//     php tools/intl/numfmt.php > crates/interp/src/intl/locales_table.rs
//
// Per locale: the patterns of the DECIMAL, PERCENT, CURRENCY,
// CURRENCY_ACCOUNTING and SCIENTIFIC styles, the number symbols, the
// numbering system's zero digit and the default currency. Currency symbols
// are stored only where a locale differs from its parent (the locale minus
// its last subtag; for a bare language, from the ISO code itself).

function lit(string $s): string
{
    $out = '';
    foreach (preg_split('//u', $s, -1, PREG_SPLIT_NO_EMPTY) as $c) {
        $o = mb_ord($c);
        $out .= match (true) {
            $c === '\\' => '\\\\',
            $c === '"' => '\\"',
            $o < 0x20 || ($o >= 0x7f && $o < 0xa0) || in_array($o, [0x200e, 0x200f, 0x061c, 0x00a0, 0x202f, 0x2009, 0x200b], true) => sprintf('\\u{%x}', $o),
            default => $c,
        };
    }
    return '"' . $out . '"';
}

$locales = ResourceBundle::getLocales('');
sort($locales);
$styles = [NumberFormatter::DECIMAL, NumberFormatter::PERCENT, NumberFormatter::CURRENCY, NumberFormatter::CURRENCY_ACCOUNTING, NumberFormatter::SCIENTIFIC];
$symbols = [
    NumberFormatter::DECIMAL_SEPARATOR_SYMBOL, NumberFormatter::GROUPING_SEPARATOR_SYMBOL, NumberFormatter::MINUS_SIGN_SYMBOL,
    NumberFormatter::PLUS_SIGN_SYMBOL, NumberFormatter::PERCENT_SYMBOL, NumberFormatter::PERMILL_SYMBOL, NumberFormatter::EXPONENTIAL_SYMBOL,
    NumberFormatter::INFINITY_SYMBOL, NumberFormatter::NAN_SYMBOL, NumberFormatter::MONETARY_SEPARATOR_SYMBOL,
    NumberFormatter::MONETARY_GROUPING_SEPARATOR_SYMBOL, NumberFormatter::ZERO_DIGIT_SYMBOL,
];

echo "// @generated by tools/intl/numfmt.php from PHP ", PHP_VERSION, " (ICU ", INTL_ICU_VERSION, "). Do not edit.\n\n";
echo "use super::numfmt::LocaleData;\n\n";
echo "/// Sorted by name.\n";
echo "pub static LOCALES: &[LocaleData] = &[\n";
$currencies = [];
foreach ($locales as $l) {
    $pat = array_map(fn ($s) => (new NumberFormatter($l, $s))->getPattern(), $styles);
    $f = new NumberFormatter($l, NumberFormatter::DECIMAL);
    $sym = array_map(fn ($s) => $f->getSymbol($s), $symbols);
    $cur = (new NumberFormatter($l, NumberFormatter::CURRENCY))->getTextAttribute(NumberFormatter::CURRENCY_CODE);
    // ICU's minimum grouping digits: 2 when 1234 stays ungrouped.
    $g = $f->getSymbol(NumberFormatter::GROUPING_SEPARATOR_SYMBOL);
    $minGroup = (!str_contains($f->format(1234), $g) && str_contains($f->format(12345), $g)) ? 2 : 1;
    if ($cur !== 'XXX') {
        $currencies[$cur] = true;
    }
    echo "    LocaleData { name: ", lit($l), ", patterns: [", implode(', ', array_map('lit', $pat)), "], symbols: [", implode(', ', array_map('lit', $sym)), "], currency: ", lit($cur), ", min_grouping: $minGroup },\n";
}
echo "];\n\n";

foreach (['XXX', 'USD', 'EUR', 'GBP', 'JPY', 'CNY', 'INR', 'AUD', 'CAD', 'CHF', 'HKD', 'SGD', 'NZD', 'KRW', 'BRL', 'MXN', 'RUB', 'ZAR', 'SEK', 'NOK', 'DKK', 'PLN', 'TRY', 'AED', 'SAR', 'ILS', 'TWD', 'THB', 'BTC'] as $c) {
    $currencies[$c] = true;
}
$currencies = array_keys($currencies);
sort($currencies);

$symbolOf = function (string $l, string $c): string {
    return (new NumberFormatter("$l@currency=$c", NumberFormatter::CURRENCY))->getSymbol(NumberFormatter::CURRENCY_SYMBOL);
};
echo "/// (locale, currency, symbol) where the locale's symbol differs from its\n";
echo "/// parent's (a bare language: from the ISO code). Sorted.\n";
echo "pub static CURRENCY_SYMBOLS: &[(&str, &str, &str)] = &[\n";
$cache = [];
foreach ($locales as $l) {
    foreach ($currencies as $c) {
        $s = $symbolOf($l, $c);
        $cache[$l][$c] = $s;
        $p = strrpos($l, '_') !== false ? substr($l, 0, strrpos($l, '_')) : null;
        $ps = $p !== null ? ($cache[$p][$c] ?? $symbolOf($p, $c)) : $c;
        if ($s !== $ps) {
            echo "    (", lit($l), ", \"$c\", ", lit($s), "),\n";
        }
    }
}
echo "];\n\n";

echo "/// ISO 4217 fraction digits where not 2.\n";
echo "pub static CURRENCY_DIGITS: &[(&str, u8)] = &[\n";
$all = [];
foreach (array_merge($currencies, ['BHD', 'CLF', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND', 'UYW', 'BIF', 'CLP', 'DJF', 'GNF', 'ISK', 'KMF', 'PYG', 'RWF', 'UGX', 'UYI', 'VND', 'VUV', 'XAF', 'XOF', 'XPF']) as $c) {
    $all[$c] = true;
}
ksort($all);
foreach (array_keys($all) as $c) {
    $f = new NumberFormatter("en@currency=$c", NumberFormatter::CURRENCY);
    $d = $f->getAttribute(NumberFormatter::MAX_FRACTION_DIGITS);
    if ($d !== 2) {
        echo "    (\"$c\", $d),\n";
    }
}
echo "];\n";
