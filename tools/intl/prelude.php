<?php
// Generate crates/interp/src/prelude_intl.php: ext/intl's classes as PHP
// declares them (constants and method signatures, by reflection). Methods
// phpx implements are natives in crates/interp/src/intl/; the rest throw.
//
//     php -n -d extension=intl tools/intl/prelude.php > crates/interp/src/prelude_intl.php

function type(?ReflectionType $t): string
{
    return $t === null ? '' : $t . ' ';
}

function param(ReflectionParameter $p): string
{
    $s = type($p->getType()) . ($p->isPassedByReference() ? '&' : '') . ($p->isVariadic() ? '...' : '') . '$' . $p->getName();
    if ($p->isOptional() && !$p->isVariadic()) {
        $s .= ' = ' . ($p->isDefaultValueAvailable() ? ($p->isDefaultValueConstant() ? '\\' . ltrim($p->getDefaultValueConstantName(), '\\') : var_export($p->getDefaultValue(), true)) : 'null');
    }
    return $s;
}

// Methods with by-reference parameters: natives return the values to
// write back.
$bodies = [
    'NumberFormatter::parse' => '[$r, $offset] = $this->__phpx_parse($string, $type, $offset); return $r;',
    'NumberFormatter::parseCurrency' => '[$r, $currency, $offset] = $this->__phpx_parse_currency($string, $offset); return $r;',
];

echo "// @generated by tools/intl/prelude.php from PHP ", PHP_VERSION, " (ICU ", INTL_ICU_VERSION, "). Do not edit.\n";
echo "// ---- ext/intl (natives in crates/interp/src/intl/) ---------------------------------------\n\n";
foreach (['IntlException', 'NumberFormatter', 'Locale'] as $name) {
    $c = new ReflectionClass($name);
    $head = $c->isFinal() ? 'final class' : 'class';
    $ext = $c->getParentClass() ? ' extends \\' . $c->getParentClass()->getName() : '';
    echo "$head $name$ext\n{\n";
    foreach ($c->getReflectionConstants() as $k) {
        if ($k->getDeclaringClass()->getName() !== $name) {
            continue;
        }
        echo "    public const ", $k->getName(), " = ", var_export($k->getValue(), true), ";\n";
    }
    foreach ($c->getMethods() as $m) {
        if ($m->getDeclaringClass()->getName() !== $name) {
            continue;
        }
        $mods = ($m->isStatic() ? 'static ' : '');
        $ret = $m->hasReturnType() ? ': ' . $m->getReturnType() : ($m->hasTentativeReturnType() ? ': ' . $m->getTentativeReturnType() : '');
        $params = implode(', ', array_map('param', $m->getParameters()));
        $body = $bodies["$name::" . $m->getName()] ?? '__phpx_intl_missing(__METHOD__);';
        echo "    public {$mods}function ", $m->getName(), "($params)$ret { $body }\n";
    }
    echo "}\n\n";
}
