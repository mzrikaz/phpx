<?php
// Generate crates/interp/src/mbcase_table.rs: the Unicode properties
// mb_convert_case() needs beyond Rust's own case mappings, from ICU.
//
//     php -n -d extension=intl tools/mbstring/case.php > crates/interp/src/mbcase_table.rs

function ranges(callable $pred): array
{
    $out = [];
    $start = null;
    for ($cp = 0; $cp <= 0x10FFFF; $cp++) {
        $in = ($cp < 0xD800 || $cp > 0xDFFF) && $pred($cp);
        if ($in && $start === null) {
            $start = $cp;
        } elseif (!$in && $start !== null) {
            $out[] = [$start, $cp - 1];
            $start = null;
        }
    }
    if ($start !== null) {
        $out[] = [$start, 0x10FFFF];
    }
    return $out;
}

function emit(string $name, string $doc, array $rows): void
{
    echo "/// $doc\npub static $name: &[(u32, u32)] = &[\n";
    foreach (array_chunk($rows, 6) as $chunk) {
        echo '    ', implode(' ', array_map(fn ($r) => sprintf('(0x%X, 0x%X),', $r[0], $r[1]), $chunk)), "\n";
    }
    echo "];\n\n";
}

echo "// @generated by tools/mbstring/case.php from ICU ", INTL_ICU_VERSION, " (Unicode ", IntlChar::UNICODE_VERSION ?? '', "). Do not edit.\n\n";
emit('CASED', 'Ranges with the Cased property.', ranges(fn ($c) => IntlChar::hasBinaryProperty($c, IntlChar::PROPERTY_CASED)));
emit('CASE_IGNORABLE', 'Ranges with the Case_Ignorable property.', ranges(fn ($c) => IntlChar::hasBinaryProperty($c, IntlChar::PROPERTY_CASE_IGNORABLE)));
$title = [];
$fold = [];
$upper = [];
for ($cp = 0; $cp <= 0x10FFFF; $cp++) {
    if ($cp >= 0xD800 && $cp <= 0xDFFF) {
        continue;
    }
    $t = IntlChar::totitle($cp);
    if ($t !== IntlChar::toupper($cp)) {
        $title[] = [$cp, $t];
    }
    // Simple uppercase where the full mapping has several characters
    // (Rust only offers the full one).
    $u = IntlChar::toupper($cp);
    if ($u !== $cp && mb_strlen(mb_strtoupper(mb_chr($cp, 'UTF-8'), 'UTF-8'), 'UTF-8') > 1) {
        $upper[] = [$cp, $u];
    }
    $f = IntlChar::foldCase($cp, IntlChar::FOLD_CASE_DEFAULT);
    if ($f !== IntlChar::tolower($cp)) {
        $fold[] = [$cp, $f];
    }
}
emit('TITLE', '(code point, simple titlecase) where it differs from simple uppercase.', $title);
emit('SIMPLE_UPPER', '(code point, simple uppercase) where the full uppercase is longer.', $upper);
emit('SIMPLE_FOLD', '(code point, simple case fold) where it differs from simple lowercase.', $fold);
